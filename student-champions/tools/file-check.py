#!/usr/bin/env python3
"""Writes FILES.md: every file to paste into the Apps Script editor, with its line count and its last line,
so a cut-off or mis-pasted file is easy to spot (scroll to the bottom of the file in the editor and compare).
Run from the student-champions folder:  python3 tools/file-check.py   (tools/build.py runs it too)
"""
import pathlib
root = pathlib.Path(__file__).resolve().parent.parent
rows = []
for f in sorted((root / "apps-script").iterdir()):
    if f.name == "appsscript.json" or f.suffix not in (".gs", ".html"):
        continue
    text = f.read_text(encoding="utf-8")
    lines = text.rstrip("\n").split("\n")
    last = lines[-1].strip()
    kind = "Script (.gs)" if f.suffix == ".gs" else "HTML"
    name = f.stem
    rows.append("| `%s` | %s | `%s` | %d | %d KB | `%s` |" % (f.name, kind, name, len(lines), round(len(text.encode()) / 1024), last.replace("|", "\\|")[:70]))
out = ("# Files to paste into the Apps Script editor\n\n"
       "Generated by `tools/file-check.py`; do not edit by hand.\n\n"
       "In the editor, use **+** then **Script** or **HTML** and give the file the name in the third column (the editor adds the extension). "
       "`appsscript.json` is pasted into the manifest file (Project Settings > show manifest).\n\n"
       "**To check a file after pasting:** scroll to the bottom. The number of the last line should equal the *Lines* column, and the last line should read as in the last column. "
       "If the file stops early, it was cut off while pasting: paste it again.\n\n"
       "| File | Type | Name in the editor | Lines | Size | Last line |\n|---|---|---|---|---|---|\n" + "\n".join(rows) + "\n")
(root / "FILES.md").write_text(out, encoding="utf-8")
print("FILES.md", len(rows), "files")
